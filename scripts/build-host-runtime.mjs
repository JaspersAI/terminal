import * as esbuild from 'esbuild'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// The runtime a plugin view's iframe loads: React, ReactDOM, zod, the SDK, and the boot script in
// one bundle, plus one shim per bare name the page's import map points at. One bundle is the point:
// the plugin's own bundle and the SDK hooks under it then share one React instance. Run by predev
// and postbuild, into out/host-runtime, which main serves over jaspers-host://runtime/.

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'out', 'host-runtime')

/** Keywords a `const { … } = ns` cannot bind. Only zod has any; they are exported under an alias. */
const RESERVED = new Set(
  'break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static await implements interface package private protected public'.split(
    ' ',
  ),
)

/** Which namespace of the runtime each bare name resolves to, and where the import map sends it. */
const SHIMS = [
  { file: 'react.js', namespace: 'React', names: await packageNames('react') },
  { file: 'jsx-runtime.js', namespace: 'JsxRuntime', names: await packageNames('react/jsx-runtime') },
  { file: 'react-dom.js', namespace: 'ReactDOM', names: await packageNames('react-dom') },
  { file: 'react-dom-client.js', namespace: 'ReactDOMClient', names: await packageNames('react-dom/client') },
  { file: 'zod.js', namespace: 'Zod', names: await packageNames('zod') },
  { file: 'sdk.js', namespace: 'Sdk', names: await sdkNames() },
]

await fs.mkdir(outDir, { recursive: true })

await esbuild.build({
  entryPoints: [path.join(root, 'src/host-runtime/runtime.ts')],
  outfile: path.join(outDir, 'runtime.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  // The SDK is a workspace package; this condition reads it from its source.
  conditions: ['jaspers-source'],
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: false,
  sourcemap: false,
  logLevel: 'warning',
})

for (const { file, namespace, names } of SHIMS) {
  await fs.writeFile(path.join(outDir, file), shim(namespace, names))
}
await fs.writeFile(path.join(outDir, 'boot.js'), "import { boot } from './runtime.js'\nboot()\n")
// The theme every view page links, the same file the app's stylesheet imports.
await fs.copyFile(path.join(root, 'src/host-runtime/theme.css'), path.join(outDir, 'theme.css'))

console.log(`host-runtime: ${SHIMS.length + 3} files in ${path.relative(root, outDir)}`)

/**
 * A shim is a real module with static named exports, since that is the only thing an import map can
 * send `import { useState } from 'react'` to. It re-exports one namespace of the runtime bundle.
 * zod exports names that are keywords (`catch`, `enum`, `void`), which can be exported but not bound,
 * so those go out under an alias.
 */
function shim(namespace, names) {
  const bindable = names.filter((name) => !RESERVED.has(name))
  const keywords = names.filter((name) => RESERVED.has(name))
  return [
    "// Generated by scripts/build-host-runtime.mjs. The iframe's import map points a bare name here.",
    `import { ${namespace} as ns } from './runtime.js'`,
    'export default ns.default ?? ns',
    `export const { ${bindable.join(', ')} } = ns`,
    ...(keywords.length > 0
      ? [
          `const { ${keywords.map((name) => `${name}: $${name}`).join(', ')} } = ns`,
          `export { ${keywords.map((name) => `$${name} as ${name}`).join(', ')} }`,
        ]
      : []),
    '',
  ].join('\n')
}

/** The names a package really exports, read from the installed package so the list cannot drift. */
async function packageNames(specifier) {
  const loaded = await import(specifier)
  return exportable(Object.keys(loaded))
}

/**
 * The SDK's, read from esbuild rather than by importing it: Node cannot load the source (its
 * relative imports have no extensions, which only a bundler resolves), and a metafile says what a
 * bundle exports without running it.
 */
async function sdkNames() {
  const built = await esbuild.build({
    stdin: { contents: "export * from '@jaspers-ai/sdk'", resolveDir: root, loader: 'ts' },
    conditions: ['jaspers-source'],
    outfile: 'sdk.js',
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    write: false,
    metafile: true,
    external: ['react', 'react-dom', 'react/jsx-runtime', 'zod'],
    logLevel: 'warning',
  })
  return exportable(Object.values(built.metafile.outputs)[0].exports)
}

/** What can be exported by name: `default` has its own line, and CJS interop adds oddities like `module.exports`. */
function exportable(names) {
  return names.filter((name) => name !== 'default' && /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name))
}
